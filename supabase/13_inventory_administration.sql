create or replace function public.configure_equipment_preventive_program(
  target_equipment_id uuid,
  target_program_id bigint,
  new_interval_months smallint,
  new_periodicity_basis text,
  new_periodicity_notes text,
  new_reference_date date,
  new_last_completed_on date
)
returns public.equipment_maintenance_programs
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_row public.equipment_maintenance_programs;
  calculated_due date;
begin
  if not public.is_manager() then
    raise exception 'Operación reservada para el rol jefe';
  end if;
  if new_interval_months is not null and new_interval_months <= 0 then
    raise exception 'La periodicidad debe ser mayor que cero';
  end if;
  if new_interval_months is not null and nullif(btrim(new_periodicity_basis), '') is null then
    raise exception 'La periodicidad requiere un fundamento';
  end if;
  if new_interval_months is not null and coalesce(new_last_completed_on, new_reference_date) is not null then
    calculated_due := (
      coalesce(new_last_completed_on, new_reference_date)::timestamp
      + make_interval(months => new_interval_months)
    )::date;
  end if;
  update public.equipment_maintenance_programs
  set interval_months = new_interval_months,
      periodicity_basis = nullif(btrim(new_periodicity_basis), ''),
      periodicity_notes = nullif(btrim(new_periodicity_notes), ''),
      reference_date = new_reference_date,
      last_completed_on = new_last_completed_on,
      next_due_on = calculated_due,
      configured_by = auth.uid(),
      configured_at = now()
  where equipment_id = target_equipment_id
    and maintenance_program_id = target_program_id
  returning * into updated_row;
  if updated_row.equipment_id is null then
    raise exception 'La rutina no está vinculada a este equipo';
  end if;
  return updated_row;
end;
$$;

create or replace function public.schedule_preventive_maintenance(
  target_equipment_id uuid,
  target_program_id bigint,
  target_scheduled_at timestamptz,
  target_assigned_to uuid default null,
  target_priority text default 'ordinaria'
)
returns public.maintenances
language plpgsql
security definer
set search_path = public
as $$
declare
  equipment_code text;
  created_row public.maintenances;
begin
  if not public.is_manager() then
    raise exception 'Operación reservada para el rol jefe';
  end if;
  if target_scheduled_at is null then
    raise exception 'La fecha programada es obligatoria';
  end if;
  if target_scheduled_at < now() then
    raise exception 'La fecha programada no puede estar en el pasado';
  end if;
  if target_priority not in ('critica', 'alta', 'ordinaria') then
    raise exception 'Prioridad no válida';
  end if;
  if target_assigned_to is not null and not exists (
    select 1 from public.profiles where id = target_assigned_to and role = 'tecnico'
  ) then
    raise exception 'La persona asignada debe tener rol técnico';
  end if;
  perform pg_advisory_xact_lock(hashtext(target_equipment_id::text || ':' || target_program_id::text));
  select ea.inventory_code into equipment_code
  from public.equipment_assets ea
  join public.equipment_maintenance_programs ep
    on ep.equipment_id = ea.id and ep.maintenance_program_id = target_program_id
  where ea.id = target_equipment_id;
  if equipment_code is null then
    raise exception 'Equipo o rutina vinculada no encontrados';
  end if;
  if exists (
    select 1 from public.maintenances
    where equipment_id = target_equipment_id
      and maintenance_program_id = target_program_id
      and scheduled_at::date = target_scheduled_at::date
      and status in ('programado', 'en_proceso')
  ) then
    raise exception 'Ya existe una orden activa para este equipo, rutina y fecha';
  end if;
  insert into public.maintenances (
    maintenance_number, maintenance_code, equipment_identifier, equipment_id,
    maintenance_program_id, status, scheduled_at, assigned_to, created_by, priority
  ) values (
    '', 'MP', equipment_code, target_equipment_id,
    target_program_id, 'programado', target_scheduled_at, target_assigned_to, auth.uid(), target_priority
  ) returning * into created_row;
  return created_row;
end;
$$;

create or replace function public.review_inventory_issue(
  target_issue_id bigint,
  new_review_status public.inventory_review_status,
  review_notes text,
  review_justification text,
  review_evidence_reference text default null
)
returns public.inventory_import_issues
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_row public.inventory_import_issues;
begin
  if not public.is_manager() then
    raise exception 'Operación reservada para el rol jefe';
  end if;
  if new_review_status = 'pendiente' then
    raise exception 'Selecciona un estado de revisión concluyente';
  end if;
  if nullif(btrim(review_notes), '') is null or nullif(btrim(review_justification), '') is null then
    raise exception 'Las observaciones y la justificación son obligatorias';
  end if;
  insert into public.inventory_issue_reviews (
    issue_id, review_status, notes, justification, evidence_reference, reviewed_by
  ) values (
    target_issue_id, new_review_status, btrim(review_notes), btrim(review_justification),
    nullif(btrim(review_evidence_reference), ''), auth.uid()
  );
  update public.inventory_import_issues
  set review_status = new_review_status,
      resolution_notes = btrim(review_notes),
      reviewed_by = auth.uid(),
      reviewed_at = now()
  where id = target_issue_id
  returning * into updated_row;
  if updated_row.id is null then
    raise exception 'Incidencia no encontrada';
  end if;
  return updated_row;
end;
$$;

