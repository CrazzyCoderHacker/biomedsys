create or replace function public.write_inventory_audit_log()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  new_row jsonb := case when tg_op = 'DELETE' then null else to_jsonb(new) end;
  old_row jsonb := case when tg_op = 'INSERT' then null else to_jsonb(old) end;
  row_identifier text;
begin
  row_identifier := coalesce(
    new_row ->> 'id', old_row ->> 'id',
    new_row ->> 'equipment_id', old_row ->> 'equipment_id',
    new_row ->> 'issue_id', old_row ->> 'issue_id'
  );
  insert into public.audit_log (actor_id, action, entity_type, entity_id, metadata)
  values (
    auth.uid(),
    tg_op,
    tg_table_name,
    row_identifier,
    jsonb_build_object('new', new_row, 'old', old_row)
  );
  return coalesce(new, old);
end;
$$;

