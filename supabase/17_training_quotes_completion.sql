begin;

create table if not exists public.quote_items (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quotes(id) on delete cascade,
  description text not null check (length(trim(description)) between 2 and 500),
  quantity numeric(12, 2) not null check (quantity > 0),
  unit_cost numeric(12, 2) not null check (unit_cost >= 0),
  line_total numeric(14, 2) generated always as (round(quantity * unit_cost, 2)) stored,
  created_at timestamptz not null default now()
);

alter table public.quote_items enable row level security;
drop policy if exists "active managers read quote items" on public.quote_items;
create policy "active managers read quote items" on public.quote_items for select to authenticated using (public.is_manager());
drop policy if exists "active managers manage quote items" on public.quote_items;
create policy "active managers manage quote items" on public.quote_items for all to authenticated using (public.is_manager()) with check (public.is_manager());
revoke all on public.quote_items from anon;
grant select, insert, update on public.quote_items to authenticated;
grant usage, select on sequence public.quote_items_id_seq to authenticated;

create or replace function public.set_training_participants(target_training_id bigint, participant_ids uuid[])
returns setof public.training_participants
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.is_technician_or_manager() then raise exception 'Permiso denegado'; end if;
  if not exists (select 1 from public.trainings where id = target_training_id) then raise exception 'Capacitación inexistente'; end if;
  if exists (select 1 from unnest(coalesce(participant_ids, array[]::uuid[])) p left join public.profiles pr on pr.id = p where pr.id is null or not pr.active) then raise exception 'Todos los participantes deben corresponder a perfiles activos'; end if;
  delete from public.training_participants where training_id = target_training_id and participant_id <> all(coalesce(participant_ids, array[]::uuid[]));
  insert into public.training_participants(training_id, participant_id)
  select target_training_id, p from unnest(coalesce(participant_ids, array[]::uuid[])) p
  on conflict (training_id, participant_id) do nothing;
  return query select * from public.training_participants where training_id = target_training_id order by participant_id;
end $$;

create or replace function public.list_active_profile_directory()
returns table(id uuid, institutional_id text, full_name text, role public.app_role, department text, active boolean)
language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if not public.is_technician_or_manager() then raise exception 'Permiso denegado'; end if;
  return query select p.id, p.institutional_id, p.full_name, p.role, p.department, p.active
  from public.profiles p where p.active order by p.full_name;
end $$;

create or replace function public.update_training_participant_attendance(target_training_id bigint, target_participant_id uuid, new_status text)
returns public.training_participants
language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.training_participants;
begin
  if not public.is_technician_or_manager() then raise exception 'Permiso denegado'; end if;
  if new_status not in ('convocado', 'confirmado', 'asistio', 'no_asistio') then raise exception 'Estado de asistencia inválido'; end if;
  update public.training_participants set attendance_status = new_status where training_id = target_training_id and participant_id = target_participant_id returning * into result;
  if result.training_id is null then raise exception 'Participante no vinculado'; end if;
  return result;
end $$;

create or replace function public.update_training_status(target_training_id bigint, new_status text)
returns public.trainings
language plpgsql security definer set search_path = public, pg_temp as $$
declare current_status text; result public.trainings;
begin
  if not public.is_technician_or_manager() then raise exception 'Permiso denegado'; end if;
  select status into current_status from public.trainings where id = target_training_id for update;
  if current_status is null then raise exception 'Capacitación inexistente'; end if;
  if not ((current_status = 'programada' and new_status in ('en_curso', 'cancelada')) or (current_status = 'en_curso' and new_status = 'completada') or current_status = new_status) then raise exception 'Transición de capacitación no permitida'; end if;
  update public.trainings set status = new_status where id = target_training_id returning * into result;
  return result;
end $$;

create or replace function public.save_quote_items(target_quote_id bigint, new_status text, items jsonb)
returns public.quotes
language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.quotes; calculated numeric(12,2);
begin
  if not public.is_manager() then raise exception 'Permiso denegado'; end if;
  if new_status not in ('pendiente', 'en_revision', 'aprobada', 'rechazada') then raise exception 'Estado inválido'; end if;
  if jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then raise exception 'Incluye al menos un concepto'; end if;
  if exists (select 1 from jsonb_to_recordset(items) x(description text, quantity numeric, unit_cost numeric) where length(trim(description)) < 2 or quantity <= 0 or unit_cost < 0) then raise exception 'Concepto inválido'; end if;
  if not exists (select 1 from public.quotes where id = target_quote_id for update) then raise exception 'Cotización inexistente'; end if;
  delete from public.quote_items where quote_id = target_quote_id;
  insert into public.quote_items(quote_id, description, quantity, unit_cost)
  select target_quote_id, trim(description), quantity, unit_cost from jsonb_to_recordset(items) x(description text, quantity numeric, unit_cost numeric);
  select coalesce(sum(line_total), 0) into calculated from public.quote_items where quote_id = target_quote_id;
  update public.quotes set amount = calculated, status = new_status where id = target_quote_id returning * into result;
  return result;
end $$;

revoke all on function public.set_training_participants(bigint, uuid[]) from public, anon;
revoke all on function public.list_active_profile_directory() from public, anon;
revoke all on function public.update_training_participant_attendance(bigint, uuid, text) from public, anon;
