grant execute on function public.list_active_profile_directory() to authenticated;
grant execute on function public.update_training_participant_attendance(bigint, uuid, text) to authenticated;
grant execute on function public.update_training_status(bigint, text) to authenticated;
grant execute on function public.save_quote_items(bigint, text, jsonb) to authenticated;

