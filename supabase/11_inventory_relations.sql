-- Additive bridge from the existing reports/maintenance modules to inventory.
-- Legacy text identifiers remain available until a validated remote import is approved.

alter table public.reports
  add column if not exists equipment_id uuid references public.equipment_assets(id);

alter table public.maintenances
  add column if not exists equipment_id uuid references public.equipment_assets(id),
  add column if not exists maintenance_program_id bigint references public.maintenance_programs(id),
  add column if not exists priority text not null default 'ordinaria'
    check (priority in ('critica', 'alta', 'ordinaria')),
  add column if not exists completed_at timestamptz;

create index if not exists reports_equipment_idx on public.reports(equipment_id);
create index if not exists maintenances_equipment_idx on public.maintenances(equipment_id);
create index if not exists maintenances_assigned_status_idx on public.maintenances(assigned_to, status);

create table if not exists public.maintenance_records (
  id bigint generated by default as identity primary key,
  maintenance_id bigint not null unique references public.maintenances(id) on delete cascade,
  performed_by uuid not null references public.profiles(id),
  started_at timestamptz,
  completed_at timestamptz,
  diagnosis text,
  work_performed text,
  test_results text,
  equipment_condition text check (equipment_condition in ('operativo', 'en_reparacion', 'fuera_de_servicio')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (completed_at is null or started_at is null or completed_at >= started_at)
);

create table if not exists public.maintenance_evidence (
  id bigint generated by default as identity primary key,
  maintenance_id bigint not null references public.maintenances(id) on delete cascade,
  uploaded_by uuid not null references public.profiles(id),
  storage_bucket text not null,
  storage_path text not null,
  evidence_type text not null check (evidence_type in ('foto', 'documento', 'firma', 'medicion', 'otro')),
  description text,
  created_at timestamptz not null default now(),
  unique (storage_bucket, storage_path)
);

drop trigger if exists maintenance_records_set_updated_at on public.maintenance_records;
create trigger maintenance_records_set_updated_at
before update on public.maintenance_records
for each row execute function public.set_inventory_updated_at();

create or replace view public.service_orders
with (security_invoker = true) as
select
  mt.id,
  mt.maintenance_number as service_order_number,
  mt.maintenance_code,
  mt.equipment_id,
  mt.equipment_identifier as legacy_equipment_identifier,
  r.id as report_id,
  r.report_number,
  mt.status,
  mt.priority,
  mt.scheduled_at,
  mt.assigned_to,
  mt.created_by,
  mt.created_at,
  mt.completed_at
from public.maintenances mt
left join public.reports r on r.maintenance_id = mt.id;
