create or replace function public.set_inventory_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists equipment_assets_set_updated_at on public.equipment_assets;
create trigger equipment_assets_set_updated_at
before update on public.equipment_assets
for each row execute function public.set_inventory_updated_at();

create or replace view public.equipment_inventory_detail
with (security_invoker = true) as
select
  ea.id,
  ea.inventory_code,
  et.name as equipment_type,
  m.name as manufacturer,
  em.name as model,
  ea.serial_number,
  ea.manufacture_year,
  ea.acquisition_year,
  ha.name as hospital_area,
  el.name as location,
  ea.custodian_location_text,
  ea.status,
  ea.requires_review,
  ra.total_score as current_risk_score,
  ra.category as current_risk_category
from public.equipment_assets ea
join public.equipment_models em on em.id = ea.equipment_model_id
join public.equipment_types et on et.id = em.equipment_type_id
join public.manufacturers m on m.id = em.manufacturer_id
join public.hospital_areas ha on ha.id = ea.hospital_area_id
left join public.equipment_locations el on el.id = ea.location_id
left join lateral (
  select r.total_score, r.category
  from public.risk_assessments r
  where r.equipment_id = ea.id
  order by r.created_at desc, r.id desc
  limit 1
) ra on true;
