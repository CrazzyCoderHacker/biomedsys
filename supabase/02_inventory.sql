create table if not exists public.hospital_areas (
  id bigint generated by default as identity primary key,
  code text unique,
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.equipment_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.manufacturers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.equipment_models (
  id bigint generated by default as identity primary key,
  equipment_type_id bigint not null references public.equipment_types(id),
  manufacturer_id bigint not null references public.manufacturers(id),
  name text not null,
  created_at timestamptz not null default now(),
