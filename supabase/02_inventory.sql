create table if not exists public.risk_assessments (
  id bigint generated by default as identity primary key,
  equipment_id uuid not null references public.equipment_assets(id) on delete cascade,
  methodology_name text not null default 'Evaluación y categorización de Equipo Médico',
  methodology_version text not null default 'Final.xlsx',
  function_score smallint not null check (function_score >= 0),
  clinical_application_score smallint not null check (clinical_application_score >= 0),
  maintenance_requirement_score smallint not null check (maintenance_requirement_score >= 0),
  total_score smallint generated always as (
    function_score + clinical_application_score + maintenance_requirement_score
  ) stored,
  category public.risk_level not null,
  assessed_at date,
  assessed_by uuid references public.profiles(id),
  source_batch_id uuid references public.inventory_import_batches(id),
  source_sheet text,
  source_row integer check (source_row is null or source_row > 0),
  created_at timestamptz not null default now(),
  constraint risk_category_matches_score check (
    (function_score + clinical_application_score + maintenance_requirement_score <= 6 and category = 'bajo') or
    (function_score + clinical_application_score + maintenance_requirement_score between 7 and 12 and category = 'medio') or
    (function_score + clinical_application_score + maintenance_requirement_score >= 13 and category = 'alto')
  ),
  unique (equipment_id, methodology_name, methodology_version)
);

create table if not exists public.inventory_import_issues (
  id bigint generated by default as identity primary key,
  source_batch_id uuid not null references public.inventory_import_batches(id) on delete cascade,
