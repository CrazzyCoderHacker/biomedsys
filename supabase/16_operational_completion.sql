begin;

create table if not exists public.file_attachments (
  id uuid primary key default gen_random_uuid(),
  bucket text not null default 'biomedgest-private'
    check (bucket = 'biomedgest-private'),
  storage_path text not null unique check (nullif(btrim(storage_path), '') is not null),
  original_name text not null check (nullif(btrim(original_name), '') is not null),
  mime_type text not null check (mime_type in (
    'application/pdf', 'image/jpeg', 'image/png', 'image/webp',
    'text/plain', 'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
  )),
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 10485760),
  uploaded_by uuid not null default auth.uid() references public.profiles(id),
  equipment_id uuid references public.equipment_assets(id),
  report_id bigint references public.reports(id),
  maintenance_id bigint references public.maintenances(id),
  training_id bigint references public.trainings(id),
  quote_id bigint references public.quotes(id),
  description text,
  created_at timestamptz not null default now(),
  constraint file_attachment_has_parent check (num_nonnulls(
    equipment_id, report_id, maintenance_id, training_id, quote_id
  ) = 1)
);

create index if not exists file_attachments_equipment_idx on public.file_attachments(equipment_id);
create index if not exists file_attachments_report_idx on public.file_attachments(report_id);
create index if not exists file_attachments_maintenance_idx on public.file_attachments(maintenance_id);

create table if not exists public.profile_change_history (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id),
  changed_by uuid not null references public.profiles(id),
  previous_role public.app_role not null,
  new_role public.app_role not null,
  previous_active boolean not null,
  new_active boolean not null,
  previous_full_name text not null,
  new_full_name text not null,
  previous_department text,
  new_department text,
  reason text not null check (nullif(btrim(reason), '') is not null),
  changed_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  event_type text not null,
  title text not null check (nullif(btrim(title), '') is not null),
  message text not null check (nullif(btrim(message), '') is not null),
  entity_type text,
  entity_id text,
  deduplication_key text not null unique,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists notifications_recipient_unread_idx
  on public.notifications(recipient_id, created_at desc) where read_at is null;

create table if not exists public.institution_settings (
  id smallint primary key default 1 check (id = 1),
  institution_name text not null default 'Institución sin configurar',
  timezone text not null default 'America/Mexico_City',
  default_currency text not null default 'MXN' check (default_currency ~ '^[A-Z]{3}$'),
  preventive_warning_days smallint not null default 30
    check (preventive_warning_days between 1 and 365),
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);
insert into public.institution_settings (id) values (1) on conflict (id) do nothing;

alter table public.file_attachments enable row level security;
