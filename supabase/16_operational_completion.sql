create or replace function public.update_own_profile(new_full_name text, new_department text)
returns public.profiles language plpgsql security definer set search_path = public
as $$
declare updated_row public.profiles;
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  if nullif(btrim(new_full_name), '') is null then raise exception 'El nombre es obligatorio'; end if;
  update public.profiles set full_name = btrim(new_full_name), department = nullif(btrim(new_department), '')
  where id = auth.uid() returning * into updated_row;
  return updated_row;
end;
$$;

create or replace function public.manage_profile(
  target_profile_id uuid,
  new_full_name text,
  new_department text,
  new_role public.app_role,
  new_active boolean,
  change_reason text
)
returns public.profiles language plpgsql security definer set search_path = public
as $$
declare old_row public.profiles; updated_row public.profiles;
begin
  if not public.is_manager() then raise exception 'Operación reservada para el rol jefe'; end if;
  if nullif(btrim(new_full_name), '') is null or nullif(btrim(change_reason), '') is null then
    raise exception 'Nombre y motivo del cambio son obligatorios';
  end if;
  select * into old_row from public.profiles where id = target_profile_id for update;
  if old_row.id is null then raise exception 'Perfil no encontrado'; end if;
  if old_row.id = auth.uid() and (new_role <> old_row.role or not new_active) then
    raise exception 'El jefe no puede cambiar su propio rol ni desactivar su perfil';
  end if;
  if (new_role = 'jefe' and left(old_row.institutional_id, 2) <> '00')
     or (new_role = 'tecnico' and left(old_row.institutional_id, 2) <> '01')
     or (new_role = 'usuario' and left(old_row.institutional_id, 2) <> '02') then
    raise exception 'El identificador institucional no corresponde al rol solicitado';
  end if;
  update public.profiles set full_name = btrim(new_full_name), department = nullif(btrim(new_department), ''),
    role = new_role, active = new_active where id = old_row.id returning * into updated_row;
  insert into public.profile_change_history (
    profile_id, changed_by, previous_role, new_role, previous_active, new_active,
    previous_full_name, new_full_name, previous_department, new_department, reason
  ) values (
    old_row.id, auth.uid(), old_row.role, updated_row.role, old_row.active, updated_row.active,
    old_row.full_name, updated_row.full_name, old_row.department, updated_row.department, btrim(change_reason)
  );
  return updated_row;
end;
$$;

create or replace function public.mark_notification_read(target_notification_id bigint, mark_read boolean default true)
returns public.notifications language plpgsql security definer set search_path = public
as $$
declare updated_row public.notifications;
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  update public.notifications set read_at = case when mark_read then now() else null end
  where id = target_notification_id and recipient_id = auth.uid()
  returning * into updated_row;
  if updated_row.id is null then raise exception 'Notificación no encontrada o no autorizada'; end if;
  return updated_row;
end;
$$;

create or replace function public.refresh_my_preventive_notifications()
returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare inserted_count integer;
begin
  if not public.has_active_profile() then raise exception 'Perfil inactivo o inexistente'; end if;
  if not public.is_technician_or_manager() then return 0; end if;
  insert into public.notifications(recipient_id, event_type, title, message, entity_type, entity_id, deduplication_key)
  select auth.uid(),
    case when m.scheduled_at::date < current_date then 'preventive_overdue' else 'preventive_upcoming' end,
    case when m.scheduled_at::date < current_date then 'Mantenimiento preventivo vencido' else 'Mantenimiento preventivo próximo' end,
    m.maintenance_number || ' · ' || coalesce(m.equipment_identifier, 'equipo vinculado') || ' · ' || m.scheduled_at::date::text,
    'maintenance', m.id::text,
    auth.uid()::text || ':preventive:' || m.id::text || ':' || m.scheduled_at::date::text
  from public.maintenances m cross join public.institution_settings s
  where m.maintenance_code = 'MP' and m.status = 'programado'
    and m.scheduled_at::date <= current_date + s.preventive_warning_days
    and (public.is_manager() or m.assigned_to = auth.uid())
  on conflict (deduplication_key) do nothing;
  get diagnostics inserted_count = row_count;
  return inserted_count;
end;
$$;

create or replace function public.update_institution_settings(
  new_institution_name text, new_timezone text, new_default_currency text,
  new_preventive_warning_days smallint
)
returns public.institution_settings language plpgsql security definer set search_path = public
as $$
declare updated_row public.institution_settings;
begin
  if not public.is_manager() then raise exception 'Operación reservada para el rol jefe'; end if;
  if nullif(btrim(new_institution_name), '') is null or nullif(btrim(new_timezone), '') is null then
    raise exception 'Institución y zona horaria son obligatorias';
  end if;
  if not exists (select 1 from pg_timezone_names where name = new_timezone) then
    raise exception 'Zona horaria no válida';
  end if;
  update public.institution_settings set institution_name = btrim(new_institution_name), timezone = new_timezone,
    default_currency = upper(new_default_currency), preventive_warning_days = new_preventive_warning_days,
    updated_by = auth.uid(), updated_at = now() where id = 1 returning * into updated_row;
  return updated_row;
end;
$$;

create or replace function public.save_preventive_intervention(
  target_maintenance_id bigint, new_started_at timestamptz, new_completed_at timestamptz,
  new_diagnosis text, new_work_performed text, new_test_results text,
  new_equipment_condition text, new_technical_notes text, new_activities jsonb default '[]'::jsonb
)
returns public.maintenance_records language plpgsql security definer set search_path = public
as $$
declare maintenance_row public.maintenances; saved_row public.maintenance_records; activity_row jsonb;
begin
  if not public.is_active_technician() then raise exception 'Operación reservada para un técnico activo'; end if;
  select * into maintenance_row from public.maintenances where id = target_maintenance_id for update;
  if maintenance_row.id is null or maintenance_row.maintenance_code <> 'MP' or maintenance_row.assigned_to <> auth.uid() then
    raise exception 'Orden preventiva no encontrada o no asignada al técnico';
  end if;
  if maintenance_row.status <> 'en_proceso' then raise exception 'La orden debe estar en proceso'; end if;
  if new_started_at is null or new_started_at > now() then raise exception 'Fecha de inicio no válida'; end if;
  if new_completed_at is not null and (new_completed_at < new_started_at or new_completed_at > now()) then
    raise exception 'Fecha de finalización no válida';
  end if;
  if jsonb_typeof(coalesce(new_activities, '[]'::jsonb)) <> 'array' then raise exception 'Actividades no válidas'; end if;
  if new_completed_at is not null and (
    nullif(btrim(new_diagnosis), '') is null or nullif(btrim(new_work_performed), '') is null
    or nullif(btrim(new_test_results), '') is null or new_equipment_condition is null
    or jsonb_array_length(new_activities) = 0
    or exists (select 1 from jsonb_array_elements(new_activities) a where coalesce((a->>'completed')::boolean, false) = false)
  ) then raise exception 'El expediente y todas las actividades son obligatorios para finalizar'; end if;

  insert into public.maintenance_records (
    maintenance_id, performed_by, started_at, completed_at, diagnosis, work_performed,
    test_results, equipment_condition, technical_notes
  ) values (
    maintenance_row.id, auth.uid(), new_started_at, new_completed_at,
    nullif(btrim(new_diagnosis), ''), nullif(btrim(new_work_performed), ''),
    nullif(btrim(new_test_results), ''), new_equipment_condition, nullif(btrim(new_technical_notes), '')
  ) on conflict (maintenance_id) do update set
    performed_by = excluded.performed_by, started_at = excluded.started_at, completed_at = excluded.completed_at,
    diagnosis = excluded.diagnosis, work_performed = excluded.work_performed,
    test_results = excluded.test_results, equipment_condition = excluded.equipment_condition,
    technical_notes = excluded.technical_notes
  returning * into saved_row;

  delete from public.maintenance_activities where maintenance_id = maintenance_row.id;
  for activity_row in select * from jsonb_array_elements(new_activities) loop
    if nullif(btrim(activity_row->>'activity'), '') is null then raise exception 'Actividad vacía'; end if;
    insert into public.maintenance_activities (maintenance_id, activity, completed, notes)
    values (maintenance_row.id, btrim(activity_row->>'activity'), coalesce((activity_row->>'completed')::boolean, false), nullif(btrim(activity_row->>'notes'), ''));
  end loop;
  return saved_row;
end;
$$;

create or replace function public.validate_preventive_closure(target_maintenance_id bigint, validation_notes text default null)
returns public.maintenances language plpgsql security definer set search_path = public
as $$
declare current_row public.maintenances; record_row public.maintenance_records; updated_row public.maintenances;
begin
  if not public.is_manager() then raise exception 'Operación reservada para el rol jefe'; end if;
  select * into current_row from public.maintenances where id = target_maintenance_id for update;
  if current_row.id is null or current_row.maintenance_code <> 'MP' or current_row.status <> 'en_proceso' then
    raise exception 'Orden preventiva no encontrada o no disponible para cierre';
  end if;
  select * into record_row from public.maintenance_records where maintenance_id = current_row.id;
  if record_row.completed_at is null then raise exception 'El técnico debe finalizar el expediente'; end if;
  update public.maintenances set status = 'completado', validated_by = auth.uid(), validated_at = now(),
    closure_notes = nullif(btrim(validation_notes), '') where id = current_row.id returning * into updated_row;
  update public.equipment_maintenance_programs
  set last_completed_on = record_row.completed_at::date,
      next_due_on = case when interval_months is not null and nullif(btrim(periodicity_basis), '') is not null
        then (record_row.completed_at::date::timestamp + make_interval(months => interval_months))::date else null end,
      updated_at = now()
  where equipment_id = current_row.equipment_id and maintenance_program_id = current_row.maintenance_program_id;
  return updated_row;
end;
$$;

-- Strengthen preventive scheduling without inventing dates or periodicities.
create or replace function public.schedule_preventive_maintenance(
  target_equipment_id uuid, target_program_id bigint, target_scheduled_at timestamptz,
  target_assigned_to uuid default null, target_priority text default 'ordinaria'
)
returns public.maintenances language plpgsql security definer set search_path = public
as $$
declare equipment_code text; created_row public.maintenances;
begin
  if not public.is_manager() then raise exception 'Operación reservada para el rol jefe'; end if;
  if target_scheduled_at is null or target_scheduled_at < now() then raise exception 'La fecha programada debe estar en el futuro'; end if;
  if target_priority not in ('critica', 'alta', 'ordinaria') then raise exception 'Prioridad no válida'; end if;
  if target_assigned_to is not null and not exists (
    select 1 from public.profiles where id = target_assigned_to and role = 'tecnico' and active
  ) then raise exception 'La persona asignada debe ser un técnico activo'; end if;
  perform pg_advisory_xact_lock(hashtext(target_equipment_id::text || ':' || target_program_id::text));
  select ea.inventory_code into equipment_code from public.equipment_assets ea
  join public.equipment_maintenance_programs ep on ep.equipment_id = ea.id and ep.maintenance_program_id = target_program_id
  where ea.id = target_equipment_id and ea.active;
  if equipment_code is null then raise exception 'Equipo activo o rutina vinculada no encontrados'; end if;
  if exists (select 1 from public.maintenances where equipment_id = target_equipment_id
    and maintenance_program_id = target_program_id and status in ('programado', 'en_proceso')) then
    raise exception 'Ya existe una orden preventiva activa para este equipo y rutina';
  end if;
  insert into public.maintenances (
    maintenance_number, maintenance_code, equipment_identifier, equipment_id,
    maintenance_program_id, status, scheduled_at, assigned_to, created_by, priority
  ) values ('', 'MP', equipment_code, target_equipment_id, target_program_id, 'programado',
    target_scheduled_at, target_assigned_to, auth.uid(), target_priority) returning * into created_row;
  return created_row;
end;
$$;

create or replace function public.emit_notification(
  target_recipient uuid, target_event_type text, target_title text, target_message text,
  target_entity_type text, target_entity_id text, target_deduplication_key text
)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if target_recipient is null then return; end if;
  insert into public.notifications (recipient_id, event_type, title, message, entity_type, entity_id, deduplication_key)
  select target_recipient, target_event_type, target_title, target_message, target_entity_type, target_entity_id, target_deduplication_key
  where exists (select 1 from public.profiles where id = target_recipient and active)
  on conflict (deduplication_key) do nothing;
end;
$$;

create or replace function public.notify_report_event()
returns trigger language plpgsql security definer set search_path = public
as $$
declare manager_id uuid;
begin
  if tg_op = 'INSERT' then
    for manager_id in select id from public.profiles where role = 'jefe' and active loop
      perform public.emit_notification(manager_id, 'nuevo_reporte', 'Nuevo reporte',
        new.report_number || ' requiere clasificación', 'reports', new.id::text,
        'report:new:' || new.id || ':' || manager_id);
    end loop;
  elsif old.status is distinct from new.status then
    perform public.emit_notification(new.reporter_id, 'estado_reporte', 'Reporte actualizado',
      new.report_number || ' cambió a ' || new.status, 'reports', new.id::text,
      'report:status:' || new.id || ':' || new.status || ':' || new.reporter_id);
  end if;
  return new;
end;
$$;

create or replace function public.notify_maintenance_event()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' and new.assigned_to is not null then
    perform public.emit_notification(new.assigned_to, 'orden_asignada', 'Nueva orden asignada',
      new.maintenance_number || ' fue asignada a tu cuenta', 'maintenances', new.id::text,
      'maintenance:assigned:' || new.id || ':' || new.assigned_to);
  elsif tg_op = 'UPDATE' and old.status is distinct from new.status then
    perform public.emit_notification(new.assigned_to, 'estado_mantenimiento', 'Orden actualizada',
      new.maintenance_number || ' cambió a ' || new.status, 'maintenances', new.id::text,
      'maintenance:status:' || new.id || ':' || new.status || ':' || coalesce(new.assigned_to::text, 'none'));
    if new.created_by is distinct from new.assigned_to then
      perform public.emit_notification(new.created_by, 'estado_mantenimiento', 'Orden actualizada',
        new.maintenance_number || ' cambió a ' || new.status, 'maintenances', new.id::text,
        'maintenance:status:' || new.id || ':' || new.status || ':' || new.created_by);
    end if;
  end if;
  return new;
end;
$$;

