alter table public.notifications enable row level security;
alter table public.institution_settings enable row level security;

create or replace function public.can_access_attachment(target_attachment_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.file_attachments fa
    where fa.id = target_attachment_id
      and public.has_active_profile()
      and (
        public.is_manager()
        or fa.uploaded_by = auth.uid()
        or (fa.equipment_id is not null and public.is_technician_or_manager())
        or exists (select 1 from public.reports r where r.id = fa.report_id and r.reporter_id = auth.uid())
        or exists (
          select 1 from public.maintenances m
          where m.id = fa.maintenance_id
            and (m.assigned_to = auth.uid() or m.created_by = auth.uid())
        )
        or exists (
          select 1 from public.trainings t
          where t.id = fa.training_id and (
            t.instructor_id = auth.uid()
            or exists (select 1 from public.training_participants tp where tp.training_id = t.id and tp.participant_id = auth.uid())
          )
        )
        or exists (select 1 from public.quotes q where q.id = fa.quote_id and q.requested_by = auth.uid())
      )
  )
$$;

create or replace function public.can_create_attachment(
  target_equipment_id uuid,
  target_report_id bigint,
  target_maintenance_id bigint,
  target_training_id bigint,
  target_quote_id bigint
)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.has_active_profile() and (
    public.is_manager()
    or (target_equipment_id is not null and public.is_technician_or_manager())
    or exists (select 1 from public.reports r where r.id = target_report_id and r.reporter_id = auth.uid())
    or exists (
      select 1 from public.maintenances m where m.id = target_maintenance_id
        and public.is_active_technician() and m.assigned_to = auth.uid()
    )
    or exists (select 1 from public.trainings t where t.id = target_training_id and t.instructor_id = auth.uid())
    or exists (select 1 from public.quotes q where q.id = target_quote_id and q.requested_by = auth.uid())
  )
$$;

