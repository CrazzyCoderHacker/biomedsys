-- Supabase Storage exists in Cloud, but not in the lightweight PostgreSQL harness.
do $$
begin
  if to_regclass('storage.buckets') is not null and to_regclass('storage.objects') is not null then
    execute $sql$insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
      values ('biomedgest-private', 'biomedgest-private', false, 10485760,
        array['application/pdf','image/jpeg','image/png','image/webp','text/plain','application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document'])
      on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types$sql$;
    execute 'drop policy if exists "authenticated upload private files" on storage.objects';
    execute $sql$create policy "authenticated upload private files" on storage.objects
      for insert to authenticated with check (
        bucket_id = 'biomedgest-private' and public.has_active_profile()
        and (storage.foldername(name))[1] = auth.uid()::text
      )$sql$;
    execute 'drop policy if exists "authorized read private files" on storage.objects';
    execute $sql$create policy "authorized read private files" on storage.objects
      for select to authenticated using (
        bucket_id = 'biomedgest-private' and exists (
          select 1 from public.file_attachments fa
          where fa.bucket = bucket_id and fa.storage_path = name and public.can_access_attachment(fa.id)
        )
      )$sql$;
    execute 'drop policy if exists "owners delete private files" on storage.objects';
    execute $sql$create policy "owners delete private files" on storage.objects
      for delete to authenticated using (
        bucket_id = 'biomedgest-private' and (
          (storage.foldername(name))[1] = auth.uid()::text
          or exists (
            select 1 from public.file_attachments fa where fa.bucket = bucket_id and fa.storage_path = name
              and public.is_manager()
          )
        )
      )$sql$;
  end if;
end $$;

commit;
