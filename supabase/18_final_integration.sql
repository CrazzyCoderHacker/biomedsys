alter table public.profiles
  add column if not exists must_change_password boolean not null default false;

alter table public.file_attachments
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid references public.profiles(id);

create index if not exists file_attachments_active_idx
  on public.file_attachments(created_at desc) where deleted_at is null;

create or replace function public.can_access_attachment(target_attachment_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.file_attachments fa
    where fa.id = target_attachment_id and fa.deleted_at is null
      and public.has_active_profile()
      and (
        public.is_manager() or fa.uploaded_by = auth.uid()
        or (fa.equipment_id is not null and public.is_technician_or_manager())
        or exists (select 1 from public.reports r where r.id = fa.report_id and r.reporter_id = auth.uid())
        or exists (select 1 from public.maintenances m where m.id = fa.maintenance_id and (m.assigned_to = auth.uid() or m.created_by = auth.uid()))
        or exists (select 1 from public.trainings t where t.id = fa.training_id and (t.instructor_id = auth.uid() or exists (
          select 1 from public.training_participants tp where tp.training_id = t.id and tp.participant_id = auth.uid()
        )))
        or exists (select 1 from public.quotes q where q.id = fa.quote_id and q.requested_by = auth.uid())
      )
  )
$$;

create or replace function public.deactivate_attachment(target_attachment_id uuid)
returns public.file_attachments language plpgsql security definer set search_path = public, pg_temp as $$
declare current_row public.file_attachments; updated_row public.file_attachments;
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  select * into current_row from public.file_attachments where id = target_attachment_id for update;
  if current_row.id is null or current_row.deleted_at is not null then raise exception 'Archivo no encontrado'; end if;
  if current_row.uploaded_by <> auth.uid() and not public.is_manager() then raise exception 'Permiso denegado'; end if;
  update public.file_attachments set deleted_at = now(), deleted_by = auth.uid()
  where id = current_row.id returning * into updated_row;
  return updated_row;
end $$;

create or replace function public.complete_password_change()
returns public.profiles language plpgsql security definer set search_path = public, pg_temp as $$
declare updated_row public.profiles;
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  update public.profiles set must_change_password = false where id = auth.uid() returning * into updated_row;
  return updated_row;
end $$;

alter table public.trainings
  add column if not exists equipment_id uuid references public.equipment_assets(id);
create index if not exists trainings_equipment_idx on public.trainings(equipment_id);

alter table public.quotes
  add column if not exists equipment_id uuid references public.equipment_assets(id),
  add column if not exists maintenance_id bigint references public.maintenances(id),
  add column if not exists updated_at timestamptz not null default now();
do $$ begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.quotes'::regclass and conname = 'quotes_single_operational_parent') then
    alter table public.quotes add constraint quotes_single_operational_parent check (num_nonnulls(equipment_id, maintenance_id) <= 1);
  end if;
end $$;
create index if not exists quotes_equipment_idx on public.quotes(equipment_id);
create index if not exists quotes_maintenance_idx on public.quotes(maintenance_id);

create table if not exists public.quote_status_history (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quotes(id) on delete cascade,
  previous_status text not null,
  new_status text not null,
  changed_by uuid not null references public.profiles(id),
  changed_at timestamptz not null default now()
);
alter table public.quote_status_history enable row level security;
drop policy if exists "active managers read quote history" on public.quote_status_history;
create policy "active managers read quote history" on public.quote_status_history
for select to authenticated using (public.is_manager());
revoke all on public.quote_status_history from anon;
grant select on public.quote_status_history to authenticated;
grant usage, select on sequence public.quote_status_history_id_seq to authenticated;

create or replace function public.save_quote_items(
  target_quote_id bigint, new_status text, items jsonb,
  target_equipment_id uuid default null, target_maintenance_id bigint default null
)
returns public.quotes language plpgsql security definer set search_path = public, pg_temp as $$
declare current_row public.quotes; result public.quotes; calculated numeric(12,2);
begin
  if not public.is_manager() then raise exception 'Permiso denegado'; end if;
  select * into current_row from public.quotes where id = target_quote_id for update;
  if current_row.id is null then raise exception 'Cotización inexistente'; end if;
  if current_row.status in ('aprobada', 'rechazada') and new_status <> current_row.status then raise exception 'Una cotización final no puede reabrirse'; end if;
  if current_row.status = 'pendiente' and new_status not in ('pendiente', 'en_revision', 'rechazada') then raise exception 'Transición de estado inválida'; end if;
  if current_row.status = 'en_revision' and new_status not in ('en_revision', 'aprobada', 'rechazada') then raise exception 'Transición de estado inválida'; end if;
  if current_row.status in ('aprobada', 'rechazada') then raise exception 'Una cotización final no puede editarse'; end if;
  if num_nonnulls(target_equipment_id, target_maintenance_id) > 1 then raise exception 'Selecciona equipo o mantenimiento, no ambos'; end if;
  if jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then raise exception 'Incluye al menos un concepto'; end if;
  if exists (select 1 from jsonb_to_recordset(items) x(description text, quantity numeric, unit_cost numeric)
    where length(trim(description)) < 2 or quantity <= 0 or unit_cost < 0) then raise exception 'Concepto inválido'; end if;
  delete from public.quote_items where quote_id = target_quote_id;
  insert into public.quote_items(quote_id, description, quantity, unit_cost)
  select target_quote_id, trim(description), quantity, unit_cost
  from jsonb_to_recordset(items) x(description text, quantity numeric, unit_cost numeric);
  select coalesce(sum(line_total), 0) into calculated from public.quote_items where quote_id = target_quote_id;
  update public.quotes set amount = calculated, status = new_status,
    equipment_id = target_equipment_id, maintenance_id = target_maintenance_id, updated_at = now()
  where id = target_quote_id returning * into result;
  if result.status <> current_row.status then
    insert into public.quote_status_history(quote_id, previous_status, new_status, changed_by)
    values (result.id, current_row.status, result.status, auth.uid());
  end if;
  return result;
end $$;

create or replace function public.get_profile_activity(target_profile_id uuid default auth.uid())
returns table(event_time timestamptz, event_type text, reference text, description text)
language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  if target_profile_id <> auth.uid() and not public.is_manager() then raise exception 'Permiso denegado'; end if;
  return query
    select r.created_at, 'report'::text, r.report_number, r.description from public.reports r where r.reporter_id = target_profile_id
    union all
    select m.created_at, 'maintenance_assignment', m.maintenance_number, coalesce(m.equipment_identifier, 'Equipo vinculado')
      from public.maintenances m where m.assigned_to = target_profile_id or m.created_by = target_profile_id
    union all
    select pch.changed_at, 'profile_change', pch.profile_id::text, pch.reason
      from public.profile_change_history pch where pch.profile_id = target_profile_id
    order by 1 desc limit 200;
end $$;

create or replace function public.get_equipment_activity(target_equipment_id uuid)
returns table(event_time timestamptz, event_type text, reference text, description text)
language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if not public.is_technician_or_manager() then raise exception 'Permiso denegado'; end if;
  return query
    select r.created_at, 'report'::text, r.report_number, r.description from public.reports r where r.equipment_id = target_equipment_id
    union all
    select m.created_at, 'maintenance'::text, m.maintenance_number, m.status from public.maintenances m where m.equipment_id = target_equipment_id
    union all
    select q.created_at, 'quote'::text, q.quote_number, q.status from public.quotes q where q.equipment_id = target_equipment_id
    union all
    select t.created_at, 'training'::text, t.training_number, t.title from public.trainings t where t.equipment_id = target_equipment_id
    order by 1 desc limit 200;
end $$;

